def ts(t):
    h=int(t//3600); m=int(t%3600//60); s=t%60
    return f"{h:02d}:{m:02d}:{int(s):02d},{int(round((s-int(s))*1000)):03d}"
def wrap(t):
    ls=textwrap.wrap(t,42)
    if len(ls)>2:  # due righe al massimo: spezzo a metà
        w=t.split(); k=len(w)//2; ls=[' '.join(w[:k]),' '.join(w[k:])]
    return '\n'.join(ls)
